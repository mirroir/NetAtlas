CREATE TABLE IF NOT EXISTS public.webauthn_challenges (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    challenge_hash bytea NOT NULL UNIQUE,

    session_binding_hash bytea NOT NULL,

    user_id integer,

    operation text NOT NULL
        CHECK (operation IN ('registration', 'authentication')),

    expires_at timestamp with time zone NOT NULL,

    consumed_at timestamp with time zone,

    created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT webauthn_challenges_user_id_fkey
        FOREIGN KEY (user_id)
        REFERENCES public.users(id)
        ON DELETE CASCADE,

    CONSTRAINT webauthn_challenges_registration_user_check
        CHECK (operation <> 'registration' OR user_id IS NOT NULL)
);

CREATE INDEX IF NOT EXISTS idx_webauthn_challenges_expires_at
    ON public.webauthn_challenges(expires_at);
