-- Autorisations temporaires de récupération.
CREATE TABLE IF NOT EXISTS public.passkey_recovery (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    user_id integer NOT NULL
        REFERENCES public.users(id)
        ON DELETE RESTRICT,

    token_hash bytea NOT NULL UNIQUE
        CHECK (octet_length(token_hash) = 32),

    expires_at timestamp with time zone NOT NULL,

    consumed_at timestamp with time zone,

    created_at timestamp with time zone
        NOT NULL DEFAULT CURRENT_TIMESTAMP,

    requested_by text NOT NULL
        CHECK (length(trim(requested_by)) > 0)
);

CREATE INDEX IF NOT EXISTS idx_passkey_recovery_user_id
    ON public.passkey_recovery(user_id);


-- Journal des opérations de récupération.
CREATE TABLE IF NOT EXISTS public.passkey_recovery_audit (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    user_id integer NOT NULL
        REFERENCES public.users(id)
        ON DELETE RESTRICT,

    action text NOT NULL
        CHECK (
            action IN (
                'requested',
                'completed',
                'failed',
                'revoked'
            )
        ),

    requested_by text NOT NULL
        CHECK (length(trim(requested_by)) > 0),

    created_at timestamp with time zone
        NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_passkey_recovery_audit_user_id
    ON public.passkey_recovery_audit(user_id);

CREATE INDEX IF NOT EXISTS idx_passkey_recovery_audit_created_at
    ON public.passkey_recovery_audit(created_at);
